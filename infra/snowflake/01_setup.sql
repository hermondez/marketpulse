USE ROLE SYSADMIN;

-- Warehouse XS con auto-suspend de 60 s: el job diario tarda ~1-2 min, así que
-- el costo es mínimo. AUTO_RESUME despierta el warehouse al recibir consultas.
CREATE WAREHOUSE IF NOT EXISTS MARKETPULSE_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'MarketPulse - proyecto educativo';

CREATE DATABASE IF NOT EXISTS MARKETPULSE;
CREATE SCHEMA IF NOT EXISTS MARKETPULSE.RAW;        -- datos crudos (ingesta Python)
CREATE SCHEMA IF NOT EXISTS MARKETPULSE.OPS;        -- alertas y salud del pipeline
CREATE SCHEMA IF NOT EXISTS MARKETPULSE.STAGING;    -- dbt prod
CREATE SCHEMA IF NOT EXISTS MARKETPULSE.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS MARKETPULSE.MARTS;
CREATE SCHEMA IF NOT EXISTS MARKETPULSE.SEEDS;
CREATE SCHEMA IF NOT EXISTS MARKETPULSE.SNAPSHOTS;

-- ---------------- Tablas RAW ----------------
CREATE TABLE IF NOT EXISTS MARKETPULSE.RAW.PRICES_DAILY (
  TICKER VARCHAR(16) NOT NULL,
  TRADE_DATE DATE NOT NULL,
  OPEN FLOAT, HIGH FLOAT, LOW FLOAT, CLOSE FLOAT, ADJ_CLOSE FLOAT,
  VOLUME NUMBER(38,0),
  SOURCE VARCHAR(32),
  INGESTED_AT TIMESTAMP_NTZ,
  CONSTRAINT PK_PRICES PRIMARY KEY (TICKER, TRADE_DATE)  -- informativa (Snowflake no la impone)
);
CREATE TABLE IF NOT EXISTS MARKETPULSE.RAW.DIVIDENDS (
  TICKER VARCHAR(16) NOT NULL,
  EX_DATE DATE NOT NULL,
  AMOUNT FLOAT,
  SOURCE VARCHAR(32),
  INGESTED_AT TIMESTAMP_NTZ,
  CONSTRAINT PK_DIVS PRIMARY KEY (TICKER, EX_DATE)
);

-- ---------------- Tablas OPS ----------------
CREATE TABLE IF NOT EXISTS MARKETPULSE.OPS.ALERTS_LOG (
  ALERT_KEY VARCHAR(200) NOT NULL PRIMARY KEY,   -- regla:ticker:fecha (deduplicación)
  RULE VARCHAR(50), TICKER VARCHAR(16), TRADE_DATE DATE,
  MESSAGE VARCHAR(4000),
  SENT_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS MARKETPULSE.OPS.DBT_RUNS (
  RUN_ID VARCHAR(64) PRIMARY KEY, GENERATED_AT VARCHAR(40), DBT_VERSION VARCHAR(20),
  COMMAND VARCHAR(30), ELAPSED_S FLOAT, N_NODES NUMBER, N_ERRORS NUMBER,
  N_WARNINGS NUMBER, STATUS VARCHAR(20)
);
CREATE TABLE IF NOT EXISTS MARKETPULSE.OPS.DBT_NODE_RESULTS (
  RUN_ID VARCHAR(64), UNIQUE_ID VARCHAR(500), RESOURCE_TYPE VARCHAR(30), NAME VARCHAR(300),
  STATUS VARCHAR(20), EXECUTION_TIME_S FLOAT, FAILURES NUMBER, MESSAGE VARCHAR(1000)
);

-- ---------------- Roles ----------------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS MARKETPULSE_LOADER;       -- ingesta, alertas, health
CREATE ROLE IF NOT EXISTS MARKETPULSE_TRANSFORMER;  -- dbt
CREATE ROLE IF NOT EXISTS MARKETPULSE_READER;       -- "Pregunta a tus datos": SOLO MARTS
GRANT ROLE MARKETPULSE_LOADER TO ROLE SYSADMIN;
GRANT ROLE MARKETPULSE_TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE MARKETPULSE_READER TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE MARKETPULSE_WH TO ROLE MARKETPULSE_LOADER;
GRANT USAGE ON WAREHOUSE MARKETPULSE_WH TO ROLE MARKETPULSE_TRANSFORMER;
GRANT USAGE ON WAREHOUSE MARKETPULSE_WH TO ROLE MARKETPULSE_READER;
GRANT USAGE ON DATABASE MARKETPULSE TO ROLE MARKETPULSE_LOADER;
GRANT USAGE ON DATABASE MARKETPULSE TO ROLE MARKETPULSE_TRANSFORMER;
GRANT USAGE ON DATABASE MARKETPULSE TO ROLE MARKETPULSE_READER;

-- LOADER: escribe RAW y OPS, lee MARTS (alertas) y crea temp tables para el MERGE.
GRANT USAGE, CREATE TABLE ON SCHEMA MARKETPULSE.RAW TO ROLE MARKETPULSE_LOADER;
GRANT USAGE, CREATE TABLE ON SCHEMA MARKETPULSE.OPS TO ROLE MARKETPULSE_LOADER;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA MARKETPULSE.RAW TO ROLE MARKETPULSE_LOADER;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA MARKETPULSE.OPS TO ROLE MARKETPULSE_LOADER;
GRANT USAGE ON SCHEMA MARKETPULSE.MARTS TO ROLE MARKETPULSE_LOADER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA MARKETPULSE.MARTS TO ROLE MARKETPULSE_LOADER;

-- TRANSFORMER: lee RAW, crea esquemas dev/ci propios y es dueño de los de prod.
GRANT USAGE ON SCHEMA MARKETPULSE.RAW TO ROLE MARKETPULSE_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA MARKETPULSE.RAW TO ROLE MARKETPULSE_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA MARKETPULSE.RAW TO ROLE MARKETPULSE_TRANSFORMER;
GRANT CREATE SCHEMA ON DATABASE MARKETPULSE TO ROLE MARKETPULSE_TRANSFORMER;
GRANT OWNERSHIP ON SCHEMA MARKETPULSE.STAGING TO ROLE MARKETPULSE_TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA MARKETPULSE.INTERMEDIATE TO ROLE MARKETPULSE_TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA MARKETPULSE.MARTS TO ROLE MARKETPULSE_TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA MARKETPULSE.SEEDS TO ROLE MARKETPULSE_TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA MARKETPULSE.SNAPSHOTS TO ROLE MARKETPULSE_TRANSFORMER COPY CURRENT GRANTS;

-- ---------------- Usuarios de servicio ----------------
CREATE USER IF NOT EXISTS MARKETPULSE_SVC PASSWORD = 'CAMBIAR_ESTO' DEFAULT_ROLE = MARKETPULSE_LOADER
  DEFAULT_WAREHOUSE = MARKETPULSE_WH MUST_CHANGE_PASSWORD = FALSE;
GRANT ROLE MARKETPULSE_LOADER TO USER MARKETPULSE_SVC;
GRANT ROLE MARKETPULSE_TRANSFORMER TO USER MARKETPULSE_SVC;
