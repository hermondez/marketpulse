-- Monitor de recursos: limita el gasto mensual del warehouse (requiere ACCOUNTADMIN).
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS MARKETPULSE_RM WITH CREDIT_QUOTA = 5 FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE MARKETPULSE_WH SET RESOURCE_MONITOR = MARKETPULSE_RM;
